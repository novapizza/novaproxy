// Writes latest.yml — the manifest that says which version is current and where
// each installer lives. It is the one file a download page, a shell script, or
// an update check has to read; everything else in the bucket is an artifact.
//
// Usage:
//   node scripts/write-release-manifest.mjs <installer-dir> [out-file]
//
// Env:
//   TAG                  release tag, e.g. v0.1.0 (default: derived from files)
//   RELEASE_BASE_URL     public prefix the installers are served from, no
//                        trailing slash (default: the GitHub release download
//                        URL built from GITHUB_REPOSITORY and TAG)
//   GITHUB_REPOSITORY    owner/repo, set by Actions
//   RELEASED_AT          ISO timestamp (default: now)
//
// The key deliberately keeps no state from previous releases: latest.yml always
// describes exactly one version, so a bad release is rolled back by rewriting
// this file, not by editing a list.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const out = process.argv[3] ?? join(dir ?? ".", "latest.yml");
if (!dir) {
  console.error("usage: node scripts/write-release-manifest.mjs <installer-dir> [out-file]");
  process.exit(1);
}

// Tauri's bundle names carry platform and arch, so the manifest is derived from
// what was actually built rather than from a hardcoded platform list — a matrix
// leg that stops shipping simply stops appearing.
const PLATFORMS = [
  { re: /_universal\.dmg$/i, key: "darwin-universal", kind: "dmg" },
  { re: /_aarch64\.dmg$/i, key: "darwin-aarch64", kind: "dmg" },
  { re: /_x64\.dmg$/i, key: "darwin-x86_64", kind: "dmg" },
  { re: /_x64-setup\.exe$/i, key: "windows-x86_64", kind: "nsis" },
  { re: /_arm64-setup\.exe$/i, key: "windows-aarch64", kind: "nsis" },
  { re: /_x64(_[a-z]{2}-[A-Z]{2})?\.msi$/, key: "windows-x86_64-msi", kind: "msi" },
];

// Recursive: upload-artifact roots an artifact at the least-common-ancestor of
// the files it matched, so a leg that produced both an NSIS installer and an MSI
// arrives as nsis/… and msi/… rather than as two files at the top level.
const files = readdirSync(dir, { recursive: true, withFileTypes: true })
  .filter((e) => e.isFile() && /\.(dmg|exe|msi)$/i.test(e.name))
  .map((e) => (e.parentPath ?? e.path) === dir ? e.name : join(e.parentPath ?? e.path, e.name).slice(dir.length + 1));
if (files.length === 0) {
  console.error(`no installers found in ${dir}`);
  process.exit(1);
}

const sha256 = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");

const entries = [];
for (const rel of files.sort()) {
  // Only the basename goes in the manifest: every installer is uploaded to the
  // bucket root, so whatever directory it arrived in is not part of its URL.
  const file = rel.split(/[\\/]/).pop();
  const match = PLATFORMS.find((p) => p.re.test(file));
  if (!match) {
    // Loud, not silent: an unrecognised artifact means the manifest would be
    // missing a platform users can otherwise download.
    console.warn(`::warning::unrecognised installer name, not in manifest: ${file}`);
    continue;
  }
  const path = join(dir, rel);
  entries.push({
    key: match.key,
    kind: match.kind,
    file,
    size: statSync(path).size,
    sha256: sha256(path),
  });
}

// Version comes from the tag when CI provides one, else from the bundle names,
// so the script is runnable by hand against a local build.
const fromName = entries.map((e) => e.file.match(/_(\d+\.\d+\.\d+)_/)?.[1]).find(Boolean);
const tag = process.env.TAG || (fromName ? `v${fromName}` : "");
const version = tag.replace(/^v/, "") || fromName;
if (!version) {
  console.error("could not determine version: pass TAG=vX.Y.Z");
  process.exit(1);
}

const repo = process.env.GITHUB_REPOSITORY;
const base = (
  process.env.RELEASE_BASE_URL ||
  (repo ? `https://github.com/${repo}/releases/download/${tag}` : "")
).replace(/\/+$/, "");
if (!base) {
  console.error("could not determine a download base: set RELEASE_BASE_URL");
  process.exit(1);
}

const releasedAt = process.env.RELEASED_AT || new Date().toISOString();
const notes = repo ? `https://github.com/${repo}/releases/tag/${tag}` : "";

// Hand-rolled YAML: the shape is fixed and shallow, so a serialiser dependency
// would buy nothing. Values are quoted, keys are known-safe identifiers.
const q = (s) => `"${String(s).replace(/(["\\])/g, "\\$1")}"`;
const lines = [
  "# Generated by scripts/write-release-manifest.mjs — do not edit by hand.",
  "# Describes the current NovaProxy release and where to download it.",
  `version: ${q(version)}`,
  `tag: ${q(tag)}`,
  `releasedAt: ${q(releasedAt)}`,
];
if (notes) lines.push(`notes: ${q(notes)}`);
lines.push("platforms:");
for (const e of entries) {
  lines.push(
    `  ${e.key}:`,
    `    kind: ${q(e.kind)}`,
    `    file: ${q(e.file)}`,
    `    url: ${q(`${base}/${encodeURIComponent(e.file)}`)}`,
    `    size: ${e.size}`,
    `    sha256: ${q(e.sha256)}`,
  );
}
const yaml = lines.join("\n") + "\n";

writeFileSync(out, yaml);
console.log(yaml);
console.log(`wrote ${out} (${entries.length} platform(s))`);
